        }
    }

    async function testConnection() {
        const url = document.getElementById('ha_url').value;
        const dot = document.getElementById('status-dot');
        const text = document.getElementById('status-text');
        const details = document.getElementById('status-details');
        const badge = document.getElementById('test-badge');

        dot.className = 'w-2 h-2 rounded-full bg-yellow-400 animate-ping';
        text.textContent = 'Testing connection...';
        details.classList.add('hidden');

        const start = Date.now();
        try {
            const res = await fetch('../api/ha_proxy.php?entity=sensor.time&_test=1&_t=' + Date.now());
            const latency = Date.now() - start;
            const data = await res.json();

            if (!data.error) {
                dot.className = 'w-2 h-2 rounded-full bg-green-400';
                text.textContent = '✓ Connected to Home Assistant!';
                text.className = 'text-green-400';
                badge.textContent = 'ONLINE';
                badge.className = 'flex px-3 py-1 rounded-full text-xs font-bold bg-green-500/10 text-green-400 border border-green-500/20';
            } else {
                throw new Error(data.error);
            }

            details.classList.remove('hidden');
            document.getElementById('sd-url').textContent = url;
            document.getElementById('sd-code').textContent = res.status;
            document.getElementById('sd-latency').textContent = latency + 'ms';
        } catch(e) {
            dot.className = 'w-2 h-2 rounded-full bg-red-400';
            text.textContent = '✗ Connection failed: ' + e.message;
            text.className = 'text-red-400';
            badge.textContent = 'OFFLINE';
            badge.className = 'flex px-3 py-1 rounded-full text-xs font-bold bg-red-500/10 text-red-400 border border-red-500/20';
        }
        badge.classList.remove('hidden');
    }
