    // ---- Admin Pattern Canvas — DPR-aware, same logic as hacontrol.php ----
    (function() {
        const canvas  = document.getElementById('pattern-canvas');
        if (!canvas) return;
        const input   = document.getElementById('pattern-input');
        const seqDisp = document.getElementById('pattern-seq-display');

        let dots = [], selected = [], drawing = false, cursor = null, size = 0;

        function init() {
            const dpr = window.devicePixelRatio || 1;
            size = canvas.offsetWidth;                  // CSS px size (200)
            canvas.width  = size * dpr;
            canvas.height = size * dpr;
            const ctx = canvas.getContext('2d');
            ctx.setTransform(1,0,0,1,0,0);
            ctx.scale(dpr, dpr);
            dots = [];
            const pad = size * 0.17, gap = (size - 2 * pad) / 2;
            for (let r = 0; r < 3; r++)
                for (let c = 0; c < 3; c++)
                    dots.push({ x: pad + c * gap, y: pad + r * gap, id: r * 3 + c + 1, active: false });
            render();
        }

        function getPos(e) {
            const rect = canvas.getBoundingClientRect();
            const t = e.touches ? e.touches[0] : e;
            return {
                x: (t.clientX - rect.left) * (size / rect.width),
                y: (t.clientY - rect.top)  * (size / rect.height)
            };
        }

        function near(pos) {
            return dots.find(d => Math.hypot(d.x - pos.x, d.y - pos.y) < size * 0.11);
        }

        function render(flash) {
            const ctx = canvas.getContext('2d');
            ctx.clearRect(0, 0, size, size);
            const col = flash === 'error'
                ? { line:'#ef4444', dot:'#ef4444', glow:'rgba(239,68,68,0.25)' }
                : { line:'#a855f7', dot:'#a855f7', glow:'rgba(168,85,247,0.2)' };

            // Connection lines
            if (selected.length > 1) {
                ctx.beginPath();
                selected.forEach((id, i) => {
                    const d = dots.find(x => x.id === id);
                    i === 0 ? ctx.moveTo(d.x, d.y) : ctx.lineTo(d.x, d.y);
                });
                ctx.strokeStyle = col.line + '99'; ctx.lineWidth = 2.5;
                ctx.lineCap = 'round'; ctx.lineJoin = 'round'; ctx.stroke();
            }
            // Trailing line
            if (drawing && cursor && selected.length) {
                const last = dots.find(d => d.id === selected[selected.length - 1]);
                ctx.beginPath(); ctx.moveTo(last.x, last.y); ctx.lineTo(cursor.x, cursor.y);
                ctx.strokeStyle = col.line + '44'; ctx.lineWidth = 2; ctx.stroke();
            }
            // Dots
            const dotR = size * 0.055;
            dots.forEach(d => {
                if (d.active) {
                    ctx.beginPath(); ctx.arc(d.x, d.y, dotR * 2, 0, Math.PI*2);
                    ctx.fillStyle = col.glow; ctx.fill();
                    ctx.beginPath(); ctx.arc(d.x, d.y, dotR * 1.3, 0, Math.PI*2);
                    ctx.strokeStyle = col.dot; ctx.lineWidth = 2; ctx.stroke();
                } else {
                    ctx.beginPath(); ctx.arc(d.x, d.y, dotR * 1.3, 0, Math.PI*2);
                    ctx.strokeStyle = 'rgba(255,255,255,0.12)'; ctx.lineWidth = 1.5; ctx.stroke();
                }
                ctx.beginPath(); ctx.arc(d.x, d.y, dotR * 0.4, 0, Math.PI*2);
                ctx.fillStyle = d.active ? col.dot : 'rgba(255,255,255,0.4)'; ctx.fill();
                // Dot number (always visible)
                ctx.font = `bold ${size * 0.04}px monospace`;
                ctx.fillStyle = d.active ? '#ffffff' : 'rgba(255,255,255,0.2)';
                ctx.textAlign = 'center'; ctx.textBaseline = 'middle';
                ctx.fillText(d.id, d.x, d.y + dotR * 2.3);
            });
        }

        function updateDisplay() {
            const seq = selected.join('');
            if (seqDisp) seqDisp.textContent = seq ? seq.split('').join(' - ') : '—';
            if (input) input.value = seq;
        }

        const onStart = e => {
            e.preventDefault();
            drawing = true; selected = [];
            dots.forEach(d => d.active = false);
            const pos = getPos(e);
            const d = near(pos);
            if (d) { d.active = true; selected.push(d.id); }
            cursor = pos; render(); updateDisplay();
        };
        const onMove = e => {
            if (!drawing) return; e.preventDefault();
            cursor = getPos(e);
            const d = near(cursor);
            if (d && !d.active) { d.active = true; selected.push(d.id); }
            render(); updateDisplay();
        };
        const onEnd = e => {
            if (!drawing) return;
            drawing = false; cursor = null; render(); updateDisplay();
            if (selected.length > 0 && selected.length < 4) {
                if (seqDisp) seqDisp.style.color = '#f59e0b';
                setTimeout(() => { if(seqDisp) seqDisp.style.color = ''; }, 1500);
            }
        };

        canvas.addEventListener('mousedown',  onStart);
        canvas.addEventListener('mousemove',  onMove);
        window.addEventListener('mouseup',    onEnd);
        canvas.addEventListener('touchstart', onStart, { passive: false });
        canvas.addEventListener('touchmove',  onMove,  { passive: false });
        canvas.addEventListener('touchend',   onEnd,   { passive: false });

        window.addEventListener('resize', init);
        init();

        window.adminPatternClear = function() {
            selected = []; dots.forEach(d => d.active = false);
            drawing = false; cursor = null;
            if (input) input.value = '';
            if (seqDisp) seqDisp.textContent = '—';
            render();
        };
    })();

